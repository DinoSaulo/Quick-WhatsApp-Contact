export function getMessages(language = "en-US") {
  return DICTIONARY[language] || DICTIONARY["en-US"];
}

export function t(messages, key, params = {}) {
  const template = messages[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, token) => {
    return params[token] ?? "";
  });
}
